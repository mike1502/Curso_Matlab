function area = area_rectangulo(base, altura)
% AREA_RECTANGULO  Calcula el área de un rectángulo.
%   area = area_rectangulo(base, altura)
%
%   Entradas:
%       base   - longitud de la base
%       altura - longitud de la altura
%   Salida:
%       area   - resultado de base * altura

area = base * altura;

end
